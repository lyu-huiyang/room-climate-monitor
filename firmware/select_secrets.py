"""PlatformIO pre-build script: pick the per-board configuration.

Writes $BUILD_DIR/rcm_config/rcm_selected_secrets.h, which config.h includes:
- RCM_ROOM=<room id> in the environment: include/secrets.<room id>.h (several boards)
- otherwise include/secrets.h if it exists (one board), else the placeholder example (CI)

The generated header uses literal #include lines so SCons tracks the chosen file: editing it
triggers a rebuild, and switching rooms leaves the compiler command line, and so the Arduino
core objects, untouched.
"""

import os
import re

Import("env")  # noqa: F821 (provided by PlatformIO)

include_dir = env.subst("$PROJECT_INCLUDE_DIR")  # noqa: F821
room = os.environ.get("RCM_ROOM", "").strip()

if room:
    if not re.fullmatch(r"[a-z0-9-]{1,32}", room):
        print(f"RCM_ROOM={room!r} is not a valid room id ([a-z0-9-]{{1,32}})")
        env.Exit(1)  # noqa: F821
    name = f"secrets.{room}.h"
    if not os.path.isfile(os.path.join(include_dir, name)):
        print(f"RCM_ROOM={room}: include/{name} not found; copy include/secrets.example.h to it and fill it in")
        env.Exit(1)  # noqa: F821
    print(f"RCM_ROOM={room}: building with include/{name}")
    lines = ["#define RCM_REAL_SECRETS 1", f'#define RCM_ROOM "{room}"', f'#include "{name}"']
elif os.path.isfile(os.path.join(include_dir, "secrets.h")):
    lines = ["#define RCM_REAL_SECRETS 1", '#include "secrets.h"']
else:
    lines = [
        '#pragma message "secrets.h not found: building with the placeholder values in secrets.example.h"',
        '#include "secrets.example.h"',
    ]

out_dir = os.path.join(env.subst("$BUILD_DIR"), "rcm_config")  # noqa: F821
out = os.path.join(out_dir, "rcm_selected_secrets.h")
content = "#pragma once\n// Generated by select_secrets.py on every build; do not edit.\n" + "\n".join(lines) + "\n"
os.makedirs(out_dir, exist_ok=True)
try:
    with open(out, encoding="utf-8") as f:
        unchanged = f.read() == content
except FileNotFoundError:
    unchanged = False
if not unchanged:  # rewriting identical content would still look like a change and rebuild
    with open(out, "w", encoding="utf-8") as f:
        f.write(content)
env.Append(CPPPATH=[out_dir])  # noqa: F821
